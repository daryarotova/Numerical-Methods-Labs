import numpy as np

# Проверка ответа из учебника (там опечатка)
A = np.array([[ 1, -1,  1, -2],
              [-9, -1,  1,  8],
              [-7,  0,  8, -6],
              [ 3, -5,  1, -6]], dtype=float)
x_book = np.array([-4, 0, -8, -4], dtype=float)
print(A @ x_book)

# ожидали: [-20, 60, -60, -44], получили: [ -4, -4, -12, 4]